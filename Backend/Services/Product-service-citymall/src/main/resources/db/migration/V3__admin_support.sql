-- Admin support: product enable/disable, category subcategories, stock movement log.
-- (ddl-auto=update applies the same change; this keeps Flyway history truthful.)

alter table if exists product
    add column if not exists active boolean not null default true;

alter table if exists category
    add column if not exists parent_id integer references category (id);

create table if not exists stock_movement
(
    id                 bigint generated by default as identity primary key,
    product_id         integer                 not null references product (id),
    quantity_change    integer                 not null,
    resulting_quantity integer                 not null,
    reason             varchar(500),
    created_at         timestamp               not null default now()
);

create index if not exists idx_stock_movement_product on stock_movement (product_id);
create index if not exists idx_product_active on product (active);
create index if not exists idx_category_parent on category (parent_id);
